package com.collectsmart.controller;

import com.collectsmart.entity.FieldOfficer;
import com.collectsmart.repository.FieldOfficerRepository;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.Map;
import java.util.Optional;

@RestController
@RequestMapping("/api/officers")
@CrossOrigin(origins = "*")
public class FieldOfficerController {

    private final FieldOfficerRepository officerRepository;

    public FieldOfficerController(
            FieldOfficerRepository officerRepository) {
        this.officerRepository = officerRepository;
    }

    // Create a new field officer - Manager only
    @PostMapping
    @PreAuthorize("hasRole('MANAGER')")
    public ResponseEntity<?> createOfficer(
            @RequestBody FieldOfficer officer) {

        // Validate officer name
        if (officer.getName() == null ||
                officer.getName().isBlank()) {

            return ResponseEntity.badRequest().body(
                    Map.of("message", "Officer name is required.")
            );
        }

        // Validate phone number
        if (officer.getPhoneNumber() == null ||
                !officer.getPhoneNumber().matches("\\d{10}")) {

            return ResponseEntity.badRequest().body(
                    Map.of("message", "Enter a valid 10-digit phone number.")
            );
        }

        // Validate pincode
        if (officer.getPincode() == null ||
                !officer.getPincode().matches("\\d{6}")) {

            return ResponseEntity.badRequest().body(
                    Map.of("message", "Enter a valid 6-digit pincode.")
            );
        }

        // Check duplicate phone number
        if (officerRepository.existsByPhoneNumber(
                officer.getPhoneNumber())) {

            return ResponseEntity.status(HttpStatus.CONFLICT).body(
                    Map.of("message", "Phone number already registered.")
            );
        }

        // Set default values
        // ID is automatically generated by JPA
        officer.setActive(true);

        if (officer.getMaxWorkload() == null ||
                officer.getMaxWorkload() <= 0) {

            officer.setMaxWorkload(20);
        }

        // Save officer
        FieldOfficer savedOfficer =
                officerRepository.save(officer);

        return ResponseEntity
                .status(HttpStatus.CREATED)
                .body(savedOfficer);
    }

    // Get all field officers - Manager only
    @GetMapping
    @PreAuthorize("hasRole('MANAGER')")
    public ResponseEntity<List<FieldOfficer>> getAllOfficers() {

        List<FieldOfficer> officers =
                officerRepository.findAll();

        return ResponseEntity.ok(officers);
    }

    // Get field officer by ID - Manager only
    @GetMapping("/{id}")
    @PreAuthorize("hasRole('MANAGER')")
    public ResponseEntity<?> getOfficerById(
            @PathVariable Long id) {

        Optional<FieldOfficer> officer =
                officerRepository.findById(id);

        if (officer.isPresent()) {
            return ResponseEntity.ok(officer.get());
        }

        return ResponseEntity.notFound().build();
    }

    // Get active field officers - Manager only
    @GetMapping("/active")
    @PreAuthorize("hasRole('MANAGER')")
    public ResponseEntity<List<FieldOfficer>> getActiveOfficers() {

        List<FieldOfficer> officers =
                officerRepository.findByActiveTrue();

        return ResponseEntity.ok(officers);
    }

    // Get active field officers by pincode - Manager only
    @GetMapping("/pincode/{pincode}")
    @PreAuthorize("hasRole('MANAGER')")
    public ResponseEntity<?> getOfficersByPincode(
            @PathVariable String pincode) {

        if (pincode == null ||
                !pincode.matches("\\d{6}")) {

            return ResponseEntity.badRequest().body(
                    Map.of("message", "Enter a valid 6-digit pincode.")
            );
        }

        List<FieldOfficer> officers =
                officerRepository.findByPincodeAndActiveTrue(pincode);

        return ResponseEntity.ok(officers);
    }
}
